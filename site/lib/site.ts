/** Canonical URL plus Open Graph and Twitter tags, so every page is indexed and shared as itself. */
export function pageMetadata({
  path,
  title,
  description,
}: {
  path: string
  title?: string
  description: string
}): Metadata {
  const url = absoluteUrl(path)
  const shareTitle = title ? `${title} | ${SITE_NAME}` : `${SITE_NAME} — ${SITE_TAGLINE}`
  return {
    ...(title ? { title } : {}),
    description,
    alternates: {
      canonical: url,
      types: { "text/plain": LLMS_TXT_URL, "text/markdown": LLMS_FULL_TXT_URL },
    },
    openGraph: {
      type: "website",
      locale: "en_US",
      url,
      siteName: SITE_NAME,
      title: shareTitle,
      description,
      images: [OG_IMAGE],
    },
    twitter: { card: "summary_large_image", title: shareTitle, description, images: [OG_IMAGE.url] },
  }
}

